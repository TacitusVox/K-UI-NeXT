"""Build the small on-console Dreamcast index from verified Libretro snapshots."""
import argparse
from collections import defaultdict
from hashlib import sha1, sha256
import json
from pathlib import Path
import re
import subprocess

DATABASE_REV = "969e31a324119a17add184e8b716315a74adb51b"
DAT_BLOB = "ce5936dceffa623a3b004a4db8a00d337330dd76"
ART_REV = "28b140d16f188301ad697e5935c6dbb412a4ceda"
ART_TREE = "d6611962ae3a24113416573834f74a9ef5d2adaf"

# IP.BIN area symbols J/U/E describe console markets. Individual European
# localizations have overlapping eligibility and remain distinct candidates.
MARKETS = {
    "Japan": 1, "Taiwan": 1, "USA": 2, "Canada": 2, "Europe": 4,
    "France": 4, "Germany": 4, "Italy": 4, "Portugal": 4, "Spain": 4,
    "Australia": 4, "India": 4, "UK": 4, "World": 7,
}
TAG = re.compile(r"\s*\(([^()]+)\)")
VARIANT = re.compile(r"(?:Disc [0-9]+|Rev [A-Z0-9]+|[A-Z][a-z](?:,[A-Z][a-z])*)")
FILENAME_PUNCT = re.compile(r'[&*/:`"<>?\\|]')


def normalized(value):
    return re.sub("[^a-z0-9]", "", value.lower())


def box_group(name):
    """Preserve region, edition and demo names while sharing retail box art."""
    return TAG.sub(lambda m: "" if VARIANT.fullmatch(m[1]) else m[0], name)


def canonical(candidates):
    # Prefer the box for the whole game. A region sometimes only has a
    # disc-specific or language-tagged box. Disc 1 represents the set there.
    return min(candidates, key=lambda name: (len(TAG.findall(name)), name))


def serial_keys(code, markets):
    code = code.upper()
    keys = {normalized(code)}
    # Redump records the US Sega catalog number without the IP.BIN MK prefix.
    if markets & 2 and re.fullmatch(r"[0-9]{5}(?:-[0-9])?", code):
        keys.add("mk" + code[:5])
    # European Sega covers carry a distribution suffix following the IP serial.
    if markets & 4 and re.fullmatch(r"MK-[0-9]{5}-50", code):
        keys.add(normalized(code[:8]))
    return {key for key in keys if key and len(key) <= 10}


def snapshot(dat, art_repo):
    data = dat.read_bytes()
    if sha1(b"blob " + str(len(data)).encode() + b"\0" + data).hexdigest() != DAT_BLOB:
        raise ValueError("unexpected Dreamcast DAT blob")
    def git(*args):
        return subprocess.check_output(["git", "-C", art_repo, *args])
    if git("rev-parse", ART_REV + ":Named_Boxarts").decode().strip() != ART_TREE:
        raise ValueError("unexpected Libretro artwork tree")
    names = git("ls-tree", "-z", "--name-only", ART_REV + ":Named_Boxarts").decode().split("\0")
    return data.decode("utf-8-sig"), sorted(name[:-4] for name in names if name.endswith(".png"))


def release_fingerprint(releases):
    return sha256("\n".join(releases).encode("ascii")).hexdigest()[:16]


def generate(dat, names):
    groups = defaultdict(list)
    for name in names:
        groups[box_group(name)].append(name)
    covers = {}
    codes = set()
    for block in re.findall(r"^game \(\s*\n(.*?)^\)", dat, re.M | re.S):
        fields = dict(re.findall(r'^\s*(name|region|serial) "([^"\n]+)"', block, re.M))
        if "name" not in fields or "region" not in fields:
            continue
        group = box_group(FILENAME_PUNCT.sub("_", fields["name"]))
        if group not in groups:
            continue
        name = canonical(groups[group])
        markets = 0
        for region in fields["region"].split(" / "):
            markets |= MARKETS[region]
        # Locate the geographic tag. Earlier parentheses can be part of the
        # retail name. Ignore version/edition tags only after the region.
        region_tag = "(" + fields["region"].replace(" / ", ", ") + ")"
        position = name.find(region_tag)
        if position < 0:
            continue
        title_end = len(name[:position].rstrip().encode())
        # A fallback from an unqualified title is appropriate only for a
        # retail edition. Serial matches can still select demos and specials.
        retail = group.endswith(region_tag)
        covers[name] = (markets, title_end, retail)
        for key in serial_keys(fields.get("serial", ""), markets):
            codes.add((key, name))
    ordered = sorted(covers)
    index = {name: i for i, name in enumerate(ordered)}
    lines = [
        "/* SPDX-License-Identifier: CC-BY-SA-4.0",
        " * Generated by tools/build_internet_cover_catalog.py from Libretro / Redump.",
        " * See docs/internet-covers.md for attribution and source snapshots. */",
        '#define KUI_BOXART_REV "' + ART_REV + '"',
        "#define KUI_BOXART_RELEASES UINT64_C(0x" + release_fingerprint(ordered) + ")",
        "static const struct cover_release cover_releases[] = {",
    ]
    for name in ordered:
        markets, length, retail = covers[name]
        if length > 255 or not name.isascii():
            raise ValueError(f"review title encoding for {name}")
        lines.append(f"    {{{json.dumps(name)}, {markets}, {length}, {int(retail)}}},")
    lines.extend(["};", "static const struct cover_serial cover_serials[] = {"])
    for key, name in sorted(codes):
        lines.append(f"    {{{json.dumps(key)}, {index[name]}}},")
    lines.extend(["};", ""])
    return "\n".join(lines), len(covers), len(codes)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dat", type=Path)
    parser.add_argument("art_repository", type=Path)
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1] / "src/apps/internet_cover_catalog.inc")
    args = parser.parse_args()
    output, covers, serials = generate(*snapshot(args.dat, args.art_repository))
    args.output.write_text(output, encoding="ascii")
    print(f"{covers} regional covers, {serials} product/cover associations")


if __name__ == "__main__":
    main()
