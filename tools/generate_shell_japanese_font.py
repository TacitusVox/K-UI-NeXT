"""Build the shell's read-only Japanese bitmap cells from its pinned JP face."""
import argparse
import hashlib
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageFont, features

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/dreamcast/shell_font_ja_data.inc"
SOURCE_HASH = "b76b0433203017ca80401b2ee0dd69350349871c4b19d504c34dbdd80541690a"
HEIGHT = 18


def characters():
    # Include official Shift-JIS punctuation spellings and CP932 vendor kanji.
    # Private-use codes are assigned by the game, so have no common glyph.
    result = set()
    for encoding in ("cp932", "shift_jis"):
        for lead in (*range(0x81, 0xA0), *range(0xE0, 0xFD)):
            for trail in range(0x40, 0xFD):
                try:
                    scalar = ord(bytes([lead, trail]).decode(encoding))
                except UnicodeDecodeError:
                    continue
                if not 0xE000 <= scalar <= 0xF8FF:
                    result.add(scalar)
    return result


def bitmap(font, scalar, width):
    mask, offset = font.getmask2(chr(scalar), mode="L", anchor="ls")
    image = Image.frombytes("L", mask.size, bytes(mask))
    bounds = image.getbbox()
    if not bounds:
        assert scalar == 0x3000
        return [0] * HEIGHT
    left, top, right, bottom = bounds
    cell = Image.new("L", (width, HEIGHT))
    ink = image.crop(bounds)
    # A few tall symbols need an extra source row or two. Keep every stroke
    # inside the same advance instead of letting glyphs collide with the UI.
    if ink.width > width or ink.height > HEIGHT:
        ink.thumbnail((width, HEIGHT), Image.Resampling.LANCZOS)
    x = max(0, min(width - ink.width, offset[0] + left))
    y = max(0, min(HEIGHT - ink.height, 15 + offset[1] + top))
    cell.paste(ink, (x, y))
    threshold = min(90, cell.getextrema()[1])
    packed = cell.point(lambda v: 255 if v >= threshold else 0, "1").tobytes()
    stride = width // 8
    rows = [int.from_bytes(packed[i:i + stride], "big") for i in range(0, len(packed), stride)]
    assert len(rows) == HEIGHT and any(rows), f"empty glyph U+{scalar:04X}"
    return rows


def array(name, values, digits, columns):
    lines = [f"static const uint{digits * 4}_t {name}[] = {{"]
    for i in range(0, len(values), columns):
        lines.append("    " + ",".join(f"0x{v:0{digits}x}" for v in values[i:i + columns]) + ",")
    return "\n".join(lines + ["};", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if hashlib.sha256(args.font.read_bytes()).hexdigest() != SOURCE_HASH:
        parser.error("use the pinned Noto Sans CJK Regular 2.004 collection")
    if features.version_module("freetype2") != "2.14.3":
        parser.error("the committed masks use FreeType 2.14.3")
    face = TTFont(args.font, fontNumber=0)
    assert face["name"].getDebugName(6) == "NotoSansCJKjp-Regular"
    wide = sorted(characters().intersection(face.getBestCmap()))
    half = range(0xFF61, 0xFFA0)
    assert len(wide) == 7331 and all(c in face.getBestCmap() for c in half)
    font = ImageFont.truetype(str(args.font), 16, index=0, layout_engine=ImageFont.Layout.BASIC)
    source = "\n".join([
        "/* SPDX-License-Identifier: OFL-1.1",
        " * Bitmap subset derived from Noto Sans CJK JP. Copyright 2014–2021 Adobe.",
        " * Generated by tools/generate_shell_japanese_font.py. See LICENSES/Noto-CJK.txt. */",
        array("japanese_scalars", wide, 4, 16),
        array("japanese_wide_rows", [v for c in wide for v in bitmap(font, c, 16)], 4, HEIGHT),
        array("japanese_half_rows", [v for c in half for v in bitmap(font, c, 8)], 4, HEIGHT),
    ])
    if args.check:
        if OUTPUT.read_bytes() != source.encode():
            raise SystemExit(f"{OUTPUT.name} differs")
    else:
        OUTPUT.write_bytes(source.encode())


if __name__ == "__main__":
    main()
