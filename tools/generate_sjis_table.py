"""Generate the Dreamcast display decoder's CP932 table using Python's codec."""

from pathlib import Path

OUTPUT = Path(__file__).resolve().parents[1] / "src/core/japanese_text_data.inc"
TRAILS = [*range(0x40, 0x7F), *range(0x80, 0xFD)]


def row_values(lead):
    values = []
    for trail in TRAILS:
        try:
            values.append(ord(bytes((lead, trail)).decode("cp932")))
        except UnicodeDecodeError:
            values.append(0)
    return values


def emit(entries, width, columns):
    return "\n".join("    " + ", ".join(f"0x{v:0{width}x}" for v in entries[i:i + columns]) + ","
                     for i in range(0, len(entries), columns))


def main():
    numbers = [0] * 256
    values = []
    for lead in [*range(0x81, 0xA0), *range(0xE0, 0xF0), *range(0xFA, 0xFD)]:
        row = row_values(lead)
        if any(row):
            numbers[lead] = len(values) // len(TRAILS) + 1
            values.extend(row)
    OUTPUT.write_text("/* SPDX-License-Identifier: GPL-3.0-only */\n"
                      "/* Generated by tools/generate_sjis_table.py. */\n"
                      "static const uint8_t sjis_rows[256] = {\n" + emit(numbers, 2, 16) + "\n};\n"
                      "static const uint16_t sjis_values[] = {\n" + emit(values, 4, 12) + "\n};\n")


if __name__ == "__main__":
    main()
